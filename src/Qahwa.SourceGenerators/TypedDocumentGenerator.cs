using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Qahwa.SourceGenerators;

/// <summary>
/// Writes a typed class for every DocType file the project lists as an AdditionalFile (see ADR-136).
/// A file is a DocType when its JSON has a "name" and a "fields" list; other JSON files are ignored.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class TypedDocumentGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Unreadable = new(
        "QWG001", "A DocType file could not be read", "The DocType file '{0}' is not valid JSON: {1}",
        "Qahwa", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor Duplicate = new(
        "QWG002", "Two DocTypes give the same class name", "The DocTypes '{0}' and '{1}' would both become the class '{2}'; the second one is skipped",
        "Qahwa", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(f => f.Path.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
            .Select((f, ct) => (f.Path, Text: f.GetText(ct)?.ToString() ?? string.Empty))
            .Collect();
        var options = context.AnalyzerConfigOptionsProvider.Select((o, _) =>
            o.GlobalOptions.TryGetValue("build_property.QahwaTypedNamespace", out var ns) && !string.IsNullOrWhiteSpace(ns) ? ns.Trim() : "Qahwa.Typed");

        context.RegisterSourceOutput(files.Combine(options), (spc, input) => Generate(spc, input.Left, input.Right));
    }

    private sealed record Field(string Name, string Type, string Options, string Label);

    private sealed record DocType(string Name, string ClassName, List<Field> Fields);

    private static void Generate(SourceProductionContext spc, IReadOnlyList<(string Path, string Text)> files, string ns)
    {
        var docTypes = new List<DocType>();
        foreach (var (path, text) in files.OrderBy(f => f.Path, StringComparer.Ordinal))
        {
            Dictionary<string, object?>? json;
            try
            {
                json = MiniJson.Parse(text) as Dictionary<string, object?>;
            }
            catch (Exception ex) when (ex is FormatException or IndexOutOfRangeException or ArgumentOutOfRangeException)
            {
                spc.ReportDiagnostic(Diagnostic.Create(Unreadable, Location.None, System.IO.Path.GetFileName(path), ex.Message));
                continue;
            }

            if (json is null || json.GetValueOrDefault("name") is not string name || json.GetValueOrDefault("fields") is not List<object?> rawFields)
                continue;
            var fields = new List<Field>();
            foreach (var raw in rawFields)
                if (raw is Dictionary<string, object?> f && f.GetValueOrDefault("name") is string fn && f.GetValueOrDefault("type") is string ft)
                    fields.Add(new Field(fn, ft, f.GetValueOrDefault("options") as string ?? string.Empty, f.GetValueOrDefault("label") as string ?? fn));
            docTypes.Add(new DocType(name, Pascal(name), fields));
        }

        var byName = new Dictionary<string, DocType>(StringComparer.OrdinalIgnoreCase);
        var classes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var docType in docTypes)
        {
            if (!classes.Add(docType.ClassName))
            {
                var first = docTypes.First(d => d.ClassName == docType.ClassName);
                spc.ReportDiagnostic(Diagnostic.Create(Duplicate, Location.None, first.Name, docType.Name, docType.ClassName));
                continue;
            }

            byName[docType.Name] = docType;
        }

        foreach (var docType in byName.Values)
            spc.AddSource($"{docType.ClassName}.g.cs", SourceText.From(Emit(docType, byName, ns), Encoding.UTF8));
    }

    private static string Emit(DocType docType, Dictionary<string, DocType> all, string ns)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>Written by Qahwa.SourceGenerators from the DocType file. Do not edit.</auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine($"/// <summary>A typed view of a '{Xml(docType.Name)}' document.</summary>");
        sb.AppendLine($"public partial class {docType.ClassName} : global::Qahwa.Abstractions.TypedDocument");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string DocType = \"{Literal(docType.Name)}\";");
        sb.AppendLine();
        sb.AppendLine($"    public {docType.ClassName}() : base(new global::System.Collections.Generic.Dictionary<string, object?>()) {{ }}");
        sb.AppendLine();
        sb.AppendLine($"    /// <summary>Wraps the values of a document (for example what GetAsync returned) without copying them.</summary>");
        sb.AppendLine($"    public {docType.ClassName}(global::System.Collections.Generic.Dictionary<string, object?> values) : base(values) {{ }}");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>The field names, for filters and sort orders.</summary>");
        sb.AppendLine("    public static class Fields");
        sb.AppendLine("    {");

        var taken = new HashSet<string>(StringComparer.Ordinal) { "Values", "Name", "Docstatus", "Creation", "Modified", "Owner", "DocType", "Fields" };
        var members = new List<(Field Field, string Property)>();
        foreach (var field in docType.Fields)
        {
            if (IsLayout(field.Type))
                continue;
            var property = Pascal(field.Name);
            while (!taken.Add(property))
                property += "Field";
            members.Add((field, property));
            sb.AppendLine($"        public const string {property} = \"{Literal(field.Name)}\";");
        }

        sb.AppendLine("    }");

        foreach (var (field, property) in members)
        {
            sb.AppendLine();
            sb.AppendLine($"    /// <summary>{Xml(field.Label)} ({field.Type}).</summary>");
            if (field.Type.Equals("Table", StringComparison.OrdinalIgnoreCase))
            {
                var row = all.TryGetValue(field.Options, out var child) ? child.ClassName : null;
                if (row is null)
                {
                    sb.AppendLine($"    public global::System.Collections.Generic.List<global::System.Collections.Generic.Dictionary<string, object?>> {property} => Rows(\"{Literal(field.Name)}\", d => d);");
                    sb.AppendLine($"    public global::System.Collections.Generic.Dictionary<string, object?> Add{property}() => AddRow(\"{Literal(field.Name)}\", d => d);");
                }
                else
                {
                    sb.AppendLine($"    public global::System.Collections.Generic.List<{row}> {property} => Rows(\"{Literal(field.Name)}\", d => new {row}(d));");
                    sb.AppendLine($"    public {row} Add{property}() => AddRow(\"{Literal(field.Name)}\", d => new {row}(d));");
                }

                continue;
            }

            var type = ClrType(field.Type);
            sb.AppendLine($"    public {type} {property}");
            sb.AppendLine("    {");
            sb.AppendLine($"        get => Get<{type}>(\"{Literal(field.Name)}\");");
            sb.AppendLine($"        set => Set(\"{Literal(field.Name)}\", value);");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static bool IsLayout(string type) =>
        type.Equals("SectionBreak", StringComparison.OrdinalIgnoreCase) || type.Equals("ColumnBreak", StringComparison.OrdinalIgnoreCase)
        || type.Equals("TabBreak", StringComparison.OrdinalIgnoreCase) || type.Equals("Heading", StringComparison.OrdinalIgnoreCase)
        || type.Equals("Html", StringComparison.OrdinalIgnoreCase);

    private static string ClrType(string type) => type.ToLowerInvariant() switch
    {
        "int" or "rating" or "duration" => "int?",
        "float" => "double?",
        "decimal" or "currency" or "percent" => "decimal?",
        "check" => "bool",
        "date" => "global::System.DateOnly?",
        "datetime" => "global::System.DateTime?",
        "time" => "global::System.TimeOnly?",
        _ => "string?",
    };

    /// <summary>"Sales Invoice" -> SalesInvoice, "customer_name" -> CustomerName; never starts with a digit.</summary>
    internal static string Pascal(string text)
    {
        var sb = new StringBuilder();
        var upper = true;
        foreach (var c in text)
        {
            if (!char.IsLetterOrDigit(c))
            {
                upper = true;
                continue;
            }

            sb.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }

        if (sb.Length == 0)
            return "Unnamed";
        return char.IsDigit(sb[0]) ? "_" + sb : sb.ToString();
    }

    private static string Literal(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n");

    private static string Xml(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
